// Companion -> game: writes answers into the LoadOnDemand slot addons and
// "rings" signal files. See addon/ForeverAICompanion/Live.lua for the other side.
import fs from 'node:fs';

export function luaString(s) {
  return '"' + String(s)
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/[\x00-\x1f\x7f]/g, (c) => '\\' + String(c.charCodeAt(0)).padStart(3, '0'))
    + '"';
}

// Words that can't be written as a bare table key.
const LUA_KEYWORDS = new Set([
  'and', 'break', 'do', 'else', 'elseif', 'end', 'false', 'for', 'function', 'goto', 'if', 'in', 'local', 'nil', 'not', 'or',
  'repeat', 'return', 'then', 'true', 'until', 'while',
]);

export function toLua(value, indent = '') {
  if (value === null || value === undefined) return 'nil';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'nil';
  if (typeof value === 'string') return luaString(value);
  const next = indent + '  ';
  if (Array.isArray(value)) {
    if (value.length === 0) return '{}';
    return '{\n' + value.map((v) => next + toLua(v, next) + ',').join('\n') + '\n' + indent + '}';
  }
  const entries = Object.entries(value).filter(([, v]) => v !== undefined && v !== null);
  if (entries.length === 0) return '{}';
  return '{\n' + entries
    .map(([k, v]) => {
      const key = /^[A-Za-z_][A-Za-z0-9_]*$/.test(k) && !LUA_KEYWORDS.has(k) ? k : `[${luaString(k)}]`;
      return `${next}${key} = ${toLua(v, next)},`;
    })
    .join('\n') + '\n' + indent + '}';
}

export function writeAtomic(file, content) {
  const tmp = `${file}.tmp-${process.pid}`;
  fs.writeFileSync(tmp, content);
  try {
    fs.renameSync(tmp, file);
  } catch (e) {
    // On Windows a file being read can block rename for a moment: retry once.
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 100);
    fs.renameSync(tmp, file);
  }
}

// 16-bit mono PCM WAV with `ms` of silence.
export function silentWav(ms = 300, rate = 22050) {
  const samples = Math.round((rate * ms) / 1000);
  const dataLen = samples * 2;
  const buf = Buffer.alloc(44 + dataLen);
  buf.write('RIFF', 0, 'latin1');
  buf.writeUInt32LE(36 + dataLen, 4);
  buf.write('WAVE', 8, 'latin1');
  buf.write('fmt ', 12, 'latin1');
  buf.writeUInt32LE(16, 16);
  buf.writeUInt16LE(1, 20); // PCM
  buf.writeUInt16LE(1, 22); // mono
  buf.writeUInt32LE(rate, 24);
  buf.writeUInt32LE(rate * 2, 28);
  buf.writeUInt16LE(2, 32);
  buf.writeUInt16LE(16, 34);
  buf.write('data', 36, 'latin1');
  buf.writeUInt32LE(dataLen, 40);
  return buf;
}

export function inboxSource(answers, extra = {}, globalName = 'ForeverAICompanion_Inbox') {
  const inbox = { v: 1, updated: Math.floor(Date.now() / 1000), ...extra, answers };
  return `-- Generated by Forever AI Companion. Do not edit.\n${globalName} = ${toLua(inbox)}\n`;
}

// Where answers go: the addon, and also the addon under the project's previous
// name while its folder is still there. A game started before the app updated
// keeps that one loaded until it is restarted, so it must keep getting answers
// (the app removes the old folder once the game is closed, see install.js).
function deliver(paths, fn) {
  fn(paths);
  const old = paths.legacy?.();
  if (old && fs.existsSync(old.addonDir)) {
    try { fn(old); } catch { /* partly removed: the current addon still got it */ }
  }
}

// A plugin's answer carries data (a talent build, a gear plan...). Only the
// newest ones keep it: the addon takes an answer the moment it arrives, and
// every mailbox file holds every answer.
export const KEEP_DATA = 4;
export function withoutOldData(answers, keep = KEEP_DATA) {
  let kept = 0;
  const out = [];
  for (let i = answers.length - 1; i >= 0; i--) {
    const a = answers[i];
    if (a && a.data !== undefined && ++kept > keep) {
      const { data, ...rest } = a;
      out.push({ ...rest, dataDropped: true });
    } else {
      out.push(a);
    }
  }
  return out.reverse();
}

export function publishInbox(paths, cfg, answers, extra = {}) {
  deliver(paths, (p) => {
    const src = inboxSource(withoutOldData(answers.slice(-cfg.keepAnswers)), extra, p.inboxGlobal);
    for (let i = 1; i <= cfg.slots; i++) {
      writeAtomic(`${p.slotDir(i)}/Inbox.lua`, src);
    }
  });
}

export function ringSignal(paths, index) {
  deliver(paths, (p) => writeAtomic(p.signal(index), silentWav()));
}

export function resetSignals(paths, cfg) {
  deliver(paths, (p) => {
    for (let i = 1; i <= cfg.signals; i++) writeAtomic(p.signal(i), Buffer.alloc(0));
  });
}
